"""Reports and exports."""

from __future__ import annotations

import html
import json

import pandas as pd
import streamlit as st
from components.ui import (
    callout,
    format_bytes,
    format_datetime,
    format_number,
    format_percentage,
    kv_row,
    metric_card,
    page_header,
    require_dataset,
    section_header,
    show_api_error,
)
from services import get_client
from services.api_client import ApiError

client = get_client()
dataset = require_dataset(client)
dataset_id = dataset["id"]

page_header(
    "Reports",
    "Download the data, quality and anomaly exports, or a consolidated JSON report "
    "assembled from persisted analysis records.",
    "Exports",
)

header_left, header_right = st.columns([3, 1])
with header_right:
    refresh = st.button("Rebuild report", width="stretch")

with st.spinner("Assembling report from stored analyses…"):
    try:
        report = client.report(dataset_id)
    except ApiError as error:
        show_api_error(error)
        st.stop()

if refresh:
    st.success("Report rebuilt from the latest persisted data.")

dataset_info = report["dataset"]
profile = report.get("profile")
anomalies = report.get("anomalies")

metric_cols = st.columns(4)
with metric_cols[0]:
    metric_card("Rows", format_number(dataset_info["row_count"]), "Original upload", "🧾", "indigo")
with metric_cols[1]:
    metric_card(
        "File size", format_bytes(dataset_info["file_size"]), "Stored on disk", "💾", "teal"
    )
with metric_cols[2]:
    metric_card(
        "Duplicate rows",
        format_number(profile["quality"]["duplicate_rows"]) if profile else "—",
        "From latest profile",
        "🧬",
        "amber",
    )
with metric_cols[3]:
    metric_card(
        "Anomalies",
        format_number(anomalies["anomalies_detected"]) if anomalies else "—",
        "Latest Isolation Forest run" if anomalies else "No run yet",
        "🎯",
        "rose",
    )

st.write("")
section_header("Downloads", "Exports are generated by the backend from the active dataset")
download_cols = st.columns(4)

base_url = client.public_base_url.rstrip("/")
with download_cols[0]:
    st.link_button(
        "Dataset CSV",
        url=f"{base_url}/api/v1/datasets/{dataset_id}/report/dataset.csv",
        width="stretch",
    )
    st.caption("Cleaned copy if available, otherwise the original.")
with download_cols[1]:
    st.link_button(
        "Quality CSV",
        url=f"{base_url}/api/v1/datasets/{dataset_id}/report/quality.csv",
        width="stretch",
    )
    st.caption("Per-column missingness and cardinality.")
with download_cols[2]:
    if anomalies:
        st.link_button(
            "Anomalies CSV",
            url=f"{base_url}/api/v1/datasets/{dataset_id}/report/anomalies.csv",
            width="stretch",
        )
        st.caption("Flagged records with scores and original columns.")
    else:
        st.button("Anomalies CSV", disabled=True, width="stretch")
        st.caption("Run anomaly detection to enable this export.")
with download_cols[3]:
    st.download_button(
        "JSON report",
        data=json.dumps(report, indent=2),
        file_name=f"insightflow_report_{dataset_id[:8]}.json",
        mime="application/json",
        width="stretch",
    )
    st.caption("Consolidated metadata, profile, anomalies and activity.")

st.write("")
left, right = st.columns([1.35, 1])

with left:
    section_header("Dataset summary")
    if profile:
        st.markdown(
            f"""
            <div class="if-card" style="margin-bottom:1rem">
              <div style="font-size:.9rem;line-height:1.7;color:#1E293B">{html.escape(profile["summary"])}</div>
            </div>
            """,
            unsafe_allow_html=True,
        )
        rows = [
            ("Dataset", dataset_info["filename"]),
            ("Rows", format_number(profile["overview"]["row_count"])),
            ("Columns", format_number(profile["overview"]["column_count"])),
            ("Missing cells", format_number(profile["quality"]["missing_cells"])),
            ("Missing share", format_percentage(profile["quality"]["missing_percentage"])),
            ("Duplicates", format_number(profile["quality"]["duplicate_rows"])),
            ("Numeric columns", format_number(profile["overview"]["numeric_column_count"])),
            (
                "Time coverage",
                format_number(len(profile["datetime_columns"])) + " datetime column(s)",
            ),
            ("Uploaded", format_datetime(dataset_info["upload_timestamp"])),
            ("Checksum", (dataset_info.get("checksum") or "—")[:16] + "…"),
        ]
        st.markdown("".join(kv_row(label, value) for label, value in rows), unsafe_allow_html=True)
    else:
        st.info("A profile could not be generated for this dataset.", icon="ℹ️")

with right:
    section_header("Anomaly summary")
    if anomalies:
        st.markdown(
            f"""
            <div class="if-card" style="margin-bottom:.8rem">
              <h4>{anomalies["anomalies_detected"]:,} records flagged
                ({anomalies["anomaly_percentage"]:.2f}%)</h4>
              <p>{html.escape(anomalies.get("interpretation") or "Isolation Forest anomaly run.")}</p>
            </div>
            """,
            unsafe_allow_html=True,
        )
        rows = [
            ("Records analyzed", format_number(anomalies["total_records"])),
            ("Contamination", format_percentage(anomalies["contamination"] * 100)),
            ("Trees", format_number(anomalies["n_estimators"])),
            ("Features", ", ".join(anomalies["features"])),
            ("Run at", format_datetime(anomalies["created_at"])),
        ]
        st.markdown("".join(kv_row(label, value) for label, value in rows), unsafe_allow_html=True)
        callout(anomalies.get("disclaimer", ""), "warn", "⚠️")
    else:
        st.info(
            "No anomaly detection run exists yet. Open Anomaly Detection to score records.",
            icon="🎯",
        )

    section_header("Assistant activity")
    chat = report.get("chat", {})
    st.markdown(
        "".join(
            kv_row(label, value)
            for label, value in [
                ("Conversations", format_number(chat.get("session_count", 0))),
                ("Messages", format_number(chat.get("message_count", 0))),
            ]
        ),
        unsafe_allow_html=True,
    )

    section_header("Quality observations")
    if profile and profile["quality_issues"]:
        for issue in profile["quality_issues"][:5]:
            st.markdown(f"- {issue}")
    else:
        st.caption("No data quality observations were recorded.")

st.write("")
section_header("Cleaning history")
history = report.get("cleaning_history") or []
if history:
    st.dataframe(
        pd.DataFrame(
            [
                {
                    "Operation": item["operation_type"].replace("_", " ").title(),
                    "Records affected": item["records_affected"],
                    "Details": str(item["operation_details"]),
                    "Recorded": format_datetime(item["created_at"]),
                }
                for item in history
            ]
        ),
        hide_index=True,
        width="stretch",
    )
else:
    st.caption("No cleaning runs recorded. The original dataset remains active.")

st.caption(
    "Reports reflect the active dataset version. Re-run cleaning or anomaly detection to "
    "refresh these exports."
)
